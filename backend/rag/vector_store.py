from pathlib import Path

import chromadb

from config import CHROMA_DIR


# ============================================================
# CONFIGURATION
# ============================================================

VECTOR_BATCH_SIZE = 100


class VectorStore:
    """
    Persistent ChromaDB vector store for CodeLens AI.

    Each repository receives its own ChromaDB collection so
    that repositories remain completely isolated during
    semantic search.
    """

    def __init__(
        self,
        chroma_path: Path = CHROMA_DIR
    ):
        self.chroma_path = Path(
            chroma_path
        )

        self.chroma_path.mkdir(
            parents=True,
            exist_ok=True
        )

        print(
            f"Loading ChromaDB from: "
            f"{self.chroma_path}"
        )

        self.client = (
            chromadb.PersistentClient(
                path=str(
                    self.chroma_path
                )
            )
        )

        print(
            "ChromaDB initialized successfully."
        )

    # ========================================================
    # COLLECTION
    # ========================================================

    def get_collection(
        self,
        repository_id: str
    ):
        """
        Get or create the ChromaDB collection for a repository.
        """

        if not repository_id:
            raise ValueError(
                "Repository ID cannot be empty."
            )

        collection_name = (
            f"repository_{repository_id}"
        )

        return self.client.get_or_create_collection(
            name=collection_name,
            metadata={
                "repository_id": repository_id
            }
        )

    # ========================================================
    # ADD CHUNKS
    # ========================================================

    def add_chunks(
        self,
        repository_id: str,
        chunks: list[dict],
        embeddings: list[list[float]]
    ) -> int:
        """
        Add repository chunks and their embeddings to ChromaDB.

        Data is inserted in batches to avoid creating one huge
        database operation for large repositories.
        """

        if not chunks:
            return 0

        if len(chunks) != len(embeddings):
            raise ValueError(
                "Number of chunks and embeddings "
                "must be identical."
            )

        collection = self.get_collection(
            repository_id
        )

        total_chunks = len(
            chunks
        )

        inserted_count = 0

        # ----------------------------------------------------
        # Insert in batches
        # ----------------------------------------------------

        for start in range(
            0,
            total_chunks,
            VECTOR_BATCH_SIZE
        ):

            end = min(
                start + VECTOR_BATCH_SIZE,
                total_chunks
            )

            batch_chunks = chunks[
                start:end
            ]

            batch_embeddings = embeddings[
                start:end
            ]

            ids = []
            documents = []
            metadatas = []

            for index, chunk in enumerate(
                batch_chunks
            ):

                metadata = chunk.get(
                    "metadata",
                    {}
                )

                content = chunk.get(
                    "content",
                    ""
                )

                # ------------------------------------------------
                # Prefer deterministic chunk ID generated by the
                # chunker.
                # ------------------------------------------------

                chunk_id = chunk.get(
                    "chunk_id"
                )

                if not chunk_id:

                    # Fallback for compatibility with older
                    # chunks that don't have chunk_id.
                    chunk_id = (
                        f"{repository_id}_"
                        f"chunk_{start + index}"
                    )

                ids.append(
                    chunk_id
                )

                documents.append(
                    content
                )

                metadatas.append(
                    metadata
                )

            collection.upsert(
                ids=ids,
                documents=documents,
                embeddings=batch_embeddings,
                metadatas=metadatas
            )

            inserted_count += len(
                batch_chunks
            )

        return inserted_count

    # ========================================================
    # SEARCH
    # ========================================================

    def search(
        self,
        repository_id: str,
        query_embedding: list[float],
        top_k: int = 5
    ) -> dict:
        """
        Search a repository's vector collection.
        """

        if not repository_id:
            raise ValueError(
                "Repository ID cannot be empty."
            )

        if not query_embedding:
            raise ValueError(
                "Query embedding cannot be empty."
            )

        if top_k <= 0:
            raise ValueError(
                "top_k must be greater than 0."
            )

        collection = self.get_collection(
            repository_id
        )

        collection_count = (
            collection.count()
        )

        # ----------------------------------------------------
        # No indexed chunks
        # ----------------------------------------------------

        if collection_count == 0:
            return {
                "documents": [[]],
                "metadatas": [[]],
                "distances": [[]],
                "ids": [[]]
            }

        result_count = min(
            top_k,
            collection_count
        )

        results = collection.query(
            query_embeddings=[
                query_embedding
            ],
            n_results=result_count,
            include=[
                "documents",
                "metadatas",
                "distances"
            ]
        )

        return results

    # ========================================================
    # COLLECTION COUNT
    # ========================================================

    def get_collection_count(
        self,
        repository_id: str
    ) -> int:
        """
        Return the number of indexed chunks for a repository.
        """

        collection = self.get_collection(
            repository_id
        )

        return collection.count()

    # ========================================================
    # DELETE REPOSITORY COLLECTION
    # ========================================================

    def delete_repository(
        self,
        repository_id: str
    ) -> None:
        """
        Delete the vector collection belonging to a repository.
        """

        if not repository_id:
            raise ValueError(
                "Repository ID cannot be empty."
            )

        collection_name = (
            f"repository_{repository_id}"
        )

        try:

            self.client.delete_collection(
                name=collection_name
            )

        except Exception:
            # If the collection doesn't exist,
            # there is nothing to delete.
            pass